package imed.moveanalysisservice.service;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import imed.moveanalysisservice.model.MoveAnalysis;
import imed.moveanalysisservice.model.MoveClassification;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;

/**
 * The Lichess ECO opening book ({@value #BOOK_FILE}, generated by {@code openings/generate-book.py}
 * from lichess-org/chess-openings). A played move is theory when every prefix of the SAN sequence
 * so far is part of a stored mainline, so the lines are expanded into a prefix set once at startup.
 * Moves that grade above GOOD (mistakes, blunders) keep their verdict: calling questionable play
 * "book" would hide its cost.
 *
 * <p>Beyond grading, the book also answers "which named opening is this?" by keeping the full
 * SAN line of every entry and resolving the longest named line that prefixes the played moves.</p>
 */
@Component
public class OpeningBook {

    private static final Logger log = LoggerFactory.getLogger(OpeningBook.class);

    static final String BOOK_FILE = "opening/opening-book-eco.json";

    /** One ECO dataset row: code, display name, and the SAN mainline. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    record BookRow(String eco, String name, List<String> san) {
    }

    /** The ECO identity of the played sequence: code and display name of the naming line. */
    public record Named(String eco, String name) {
    }

    private final Set<String> prefixes = new java.util.HashSet<>();
    private final Map<String, Named> named = new HashMap<>();

    public OpeningBook(ObjectMapper objectMapper) {
        List<BookRow> rows = readRows(objectMapper);
        int skipped = 0;
        for (BookRow row : rows) {
            if (row.san() == null || row.san().isEmpty() || row.eco() == null || row.name() == null) {
                skipped++;
                continue;
            }
            List<String> moves = row.san().stream().map(OpeningBook::canonical).toList();
            for (int to = 1; to <= moves.size(); to++) {
                prefixes.add(String.join(" ", moves.subList(0, to)));
            }
            // The dataset repeats rows for transposition coverage; the first name wins for a
            // canonicalised line, which keeps identity resolution stable run to run.
            named.putIfAbsent(String.join(" ", moves), new Named(row.eco(), row.name()));
        }
        log.info("Opening book loaded: {} ECO lines, {} prefix positions, {} unusable rows",
                named.size(), prefixes.size(), skipped);
    }

    /** True when the SAN moves ending at {@code throughIndex} (inclusive) all sit on a mainline. */
    public boolean isBook(List<String> sans, int throughIndex) {
        if (throughIndex < 0 || throughIndex >= sans.size()) {
            return false;
        }
        List<String> prefix = new ArrayList<>(throughIndex + 1);
        for (int i = 0; i <= throughIndex; i++) {
            prefix.add(canonical(sans.get(i)));
        }
        return prefixes.contains(String.join(" ", prefix));
    }

    /**
     * The deepest named ECO line that prefixes {@code sans}, or empty when the sequence left the
     * book before ever matching a named line. Playing on past a named line keeps that line as the
     * identity — theory extensions of an opening are still that opening.
     */
    public Optional<Named> nameOf(List<String> sans) {
        List<String> canonical = new ArrayList<>(sans.size());
        for (String san : sans) {
            canonical.add(canonical(san));
        }
        for (int to = canonical.size(); to >= 1; to--) {
            Named match = named.get(String.join(" ", canonical.subList(0, to)));
            if (match != null) {
                return Optional.of(match);
            }
        }
        return Optional.empty();
    }

    /** Marks stored rows that are theory; rows must already be ordered ply ascending. */
    public void apply(List<MoveAnalysis> rows) {
        List<String> sans = new ArrayList<>(rows.size());
        for (int index = 0; index < rows.size(); index++) {
            String san = rows.get(index).getSan();
            if (san == null || san.isBlank()) {
                sans.add("");
                continue;
            }
            sans.add(san);
            MoveClassification current = rows.get(index).getClassification();
            if ((current == null || current == MoveClassification.GOOD)
                    && nvl(rows.get(index).getPly()) > 0
                    && isBook(sans, index)) {
                rows.get(index).setClassification(MoveClassification.BOOK);
            }
        }
    }

    /**
     * Chess.js and SanCodec disagree on check marks and digit castling, so annotations and
     * notation variants never take part in matching.
     */
    static String canonical(String san) {
        String trimmed = san.trim().replaceAll("[+#!?]+$", "").toUpperCase(Locale.ROOT);
        return trimmed.replace("0-0-0", "O-O-O").replace("0-0", "O-O");
    }

    private static int nvl(Integer value) {
        return value == null ? 0 : value;
    }

    private static List<BookRow> readRows(ObjectMapper objectMapper) {
        try (InputStream in = new ClassPathResource(BOOK_FILE).getInputStream()) {
            return objectMapper.readValue(in, new TypeReference<>() { });
        } catch (Exception exception) {
            log.warn("No opening book resource; BOOK moves will not be graded: {}", exception.getMessage());
            return List.of();
        }
    }
}
